import { useEffect, useRef, useState } from "react";
import { useTranslation } from "react-i18next";
import { faPause, faPlay } from "@fortawesome/free-solid-svg-icons";
import manifest from "@/data/media.json";
import Icon from "./Icon";
import { useInView, usePrefersReducedMotion } from "./motion";

type Variant = { width: number; src: string };
type Entry = {
  width: number;
  height: number;
  variants?: Variant[];
  video?: string;
  poster?: string;
};

const media = manifest as Record<string, Entry>;

type Props = {
  /** Path of the original picture inside public/img, e.g. "portfolio/dino.png". */
  src: string;
  alt: string;
  /** CSS width the picture takes, used to pick the lightest file. */
  sizes?: string;
  className?: string;
  /** Above-the-fold pictures load immediately. */
  eager?: boolean;
};

/** Optimized picture with reserved space, generated by `npm run media`. */
export function Picture({ src, alt, sizes, className, eager }: Props) {
  const entry = media[src];
  if (!entry) {
    return (
      <img src={`/img/${src}`} alt={alt} className={className} loading="lazy" />
    );
  }
  if (!entry.variants) {
    // Clips are represented by their first frame.
    return (
      <img
        className={className}
        src={entry.poster}
        width={entry.width}
        height={entry.height}
        alt={alt}
        loading="lazy"
        decoding="async"
      />
    );
  }
  const largest = entry.variants[entry.variants.length - 1];
  return (
    <img
      className={className}
      src={largest.src}
      srcSet={entry.variants.map((v) => `${v.src} ${v.width}w`).join(", ")}
      sizes={sizes ?? "(min-width: 60rem) 44rem, 92vw"}
      width={entry.width}
      height={entry.height}
      alt={alt}
      loading={eager ? "eager" : "lazy"}
      decoding="async"
      fetchPriority={eager ? "high" : undefined}
    />
  );
}

/**
 * Former GIF served as a small looping video. It plays only while visible,
 * never when reduced motion is requested, and can always be paused.
 */
function Clip({ src, alt, className }: Props) {
  const { t } = useTranslation();
  const entry = media[src];
  const reduced = usePrefersReducedMotion();
  const [frameRef, inView] = useInView<HTMLDivElement>();
  const videoRef = useRef<HTMLVideoElement>(null);
  const [wanted, setWanted] = useState(!reduced);
  const [playing, setPlaying] = useState(false);

  useEffect(() => {
    const video = videoRef.current;
    if (!video) return;
    if (wanted && inView) video.play().catch(() => setPlaying(false));
    else video.pause();
  }, [wanted, inView]);

  return (
    <div className={className ? `clip ${className}` : "clip"} ref={frameRef}>
      <video
        ref={videoRef}
        src={entry.video}
        poster={entry.poster}
        width={entry.width}
        height={entry.height}
        muted
        loop
        playsInline
        preload="none"
        aria-label={alt}
        onPlay={() => setPlaying(true)}
        onPause={() => setPlaying(false)}
      />
      <button
        type="button"
        className="clip-toggle"
        onClick={() => setWanted(!playing)}
        aria-label={playing ? t("ui.pauseAnimation") : t("ui.playAnimation")}
        aria-pressed={playing}
      >
        <Icon icon={playing ? faPause : faPlay} />
      </button>
    </div>
  );
}

type FigureProps = Props & { caption?: boolean };

/** Picture or clip, with its description shown as a caption on demand. */
export default function Figure({ caption, ...props }: FigureProps) {
  const isClip = Boolean(media[props.src]?.video);
  return (
    <figure className="figure">
      {isClip ? <Clip {...props} /> : <Picture {...props} />}
      {caption && <figcaption>{props.alt}</figcaption>}
    </figure>
  );
}
